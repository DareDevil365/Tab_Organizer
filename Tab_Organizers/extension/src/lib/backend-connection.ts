/** One device connection, shared by the dashboard, popup and service worker. */
export const LOCAL_BACKEND='http://127.0.0.1:8742';
export const CONNECTION_KEY='backend_connection';
export interface BackendConnection { url: string; key: string }

export function normalizeBackendUrl(value: string): string {
  const url=new URL(value.trim());
  const local=['localhost','127.0.0.1','[::1]'].includes(url.hostname);
  if(url.username||url.password||url.search||url.hash||url.pathname!=='/'||(url.protocol!=='https:'&&!(local&&url.protocol==='http:')))throw new Error('Use an HTTPS backend address without a path. Localhost may use HTTP.');
  return url.origin;
}

export async function getBackendConnection(): Promise<BackendConnection> {
  let value: BackendConnection | undefined;
  if(typeof chrome!=='undefined'&&chrome.storage?.local)value=(await chrome.storage.local.get(CONNECTION_KEY))[CONNECTION_KEY];
  else if(typeof localStorage!=='undefined'){
    try{value=JSON.parse(localStorage.getItem(CONNECTION_KEY)||'null');}catch{/* A fresh preview uses local mode. */}
  }
  if(!value)return {url:LOCAL_BACKEND,key:''};
  try{return {url:normalizeBackendUrl(value.url),key:typeof value.key==='string'?value.key:''};}
  catch{throw new Error('The saved backend address is invalid. Update it in Settings.');}
}

async function store(connection: BackendConnection): Promise<void> {
  const cached=['companion_notes','saved_tab_groups'];
  if(typeof chrome!=='undefined'&&chrome.storage?.local){
    const previous=await getBackendConnection();
    const old=await chrome.storage.local.get('companion_notes');
    const pending=Array.isArray(old.companion_notes)?old.companion_notes.filter((note:{pendingSync?:boolean})=>note.pendingSync):[];
    await chrome.storage.local.set({['backend_drafts:'+previous.url]:pending});
    const bank=await chrome.storage.local.get('backend_drafts:'+connection.url);
    await chrome.storage.local.set({[CONNECTION_KEY]:connection});
    // Synced caches from another backend must not appear as cloud library data.
    await chrome.storage.local.remove(cached);
    await chrome.storage.local.set({companion_notes:bank['backend_drafts:'+connection.url] || []});
  }else if(typeof localStorage!=='undefined'){
    localStorage.setItem(CONNECTION_KEY,JSON.stringify(connection));cached.forEach(key=>localStorage.removeItem(key));
  }
  if(typeof window!=='undefined')window.dispatchEvent(new Event('backend-connection-changed'));
}

export async function connectBackend(url: string, key: string): Promise<void> {
  const connection={url:normalizeBackendUrl(url),key:key.trim()};
  if(connection.url!==LOCAL_BACKEND&&connection.key.length<32)throw new Error('Paste the private connection key generated by cloud setup.');
  const response=await fetch(connection.url+'/auth/session',{headers:connection.key?{Authorization:'Bearer '+connection.key}:{},signal:AbortSignal.timeout(15000)});
  if(response.status===401)throw new Error('The connection key is incorrect.');
  if(!response.ok)throw new Error('The backend is not ready. Check the deployment and try again.');
  const result=await response.json().catch(()=>null);
  if(result?.connected!==true)throw new Error('This address is not a Tab Organizer backend.');
  await store(connection);
}

export async function useLocalBackend(): Promise<void> {
  await store({url:LOCAL_BACKEND,key:''});
}
